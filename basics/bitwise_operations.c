// bit wise operations

#include <stdio.h>

int main()
{
    int a = 8, b = 1;
    printf("AND OPERATION a&b is %d\n", a & b);
    printf("OR OPERATION a|b is %d\n", a | b);
    printf("NOT OPERATION ~a is %d\n", ~a);
    printf("XOR OPERATION a^b is %d\n", a ^ b);
    printf("LEFT SHIFT OPERATION a<<b is %d\n", a << b);
    printf("RIGHT SHIFT OPERATION a>>b is %d\n",a>>b);
    return 0;


}