// c proogram for bitwise operator
#include <stdio.h>

int main()
{
    int a = 5, b = 9;
   printf("a & b = %d\n", a & b);
   printf("a | b = %d\n", a | b);
   printf("a ^ b = %d\n", a ^ b);
   printf("!a = %d\n", ~a);
   printf("~b = %d\n", ~b);
   printf("a << 1 = %d\n", a << 1);
   printf("a >> 1 = %d\n", a >> 1);

}